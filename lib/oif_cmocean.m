if nargin < 2 || isempty(NLevels)
    NLevels = 256;
end
name = char(name);
reverse = strncmp(name, '-', 1);
if reverse
    name = name(2:end);
end
switch lower(name)
    case 'balance'
        rgb = balance_rgb();
    case 'amp'
        rgb = amp_rgb();
    otherwise
        error('oif_cmocean:name', ['Colormap ''%s'' is not included in this minimal ' ...
            'version (only ''balance'' and ''amp'').'], name);
end
n = size(rgb, 1);
if NLevels ~= n
    rgb = interp1((1:n)', rgb, linspace(1, n, NLevels)');
end
if reverse
    rgb = flipud(rgb);
end
if nargout == 0
    colormap(gca, rgb);
else
    cmap = rgb;
end
end

