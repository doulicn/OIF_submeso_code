function cmap = oif_cmocean(name, NLevels)
%OIF_CMOCEAN  cmocean 'balance' and 'amp' colormaps (minimal version for this package).
%
%   cmap = oif_cmocean(name)            256 x 3 colormap
%   cmap = oif_cmocean(name, NLevels)   NLevels x 3 colormap, resampled linearly
%   oif_cmocean(...)                    without an output: applies the
%                                       colormap to the current axes
%
%   name   'balance' (diverging) or 'amp' (sequential); a leading '-'
%          reverses the colormap (e.g. '-amp')
%
%   Only the two colormaps used by this package are included ('amp': Figs.
%   1f-h, S5 and S6; 'balance': Figs. S12 and S13). The 256 x 3 RGB tables
%   are those of the cmocean colormaps by Kristen M. Thyng, as distributed
%   with the MATLAB function cmocean.m by Chad A. Greene. Resampling to
%   NLevels is the linear interpolation over the 256 entries of that
%   function, so the colormaps used here are identical to its output
%   (checked before release); a reversed colormap is flipped after the
%   resampling (Greene's function flips first, which can differ by
%   round-off). The function code itself was written for this package. It
%   is named oif_cmocean so that it does not shadow a full cmocean.m on the
%   MATLAB path.
%
%   Please cite: Thyng, K. M., C. A. Greene, R. D. Hetland, H. M. Zimmerle,
%   and S. F. DiMarco (2016), True colors of oceanography: Guidelines for
%   effective and accurate colormap selection, Oceanography, 29(3), 9-13,
%   https://doi.org/10.5670/oceanog.2016.66
%
%   cmocean colormaps, https://github.com/matplotlib/cmocean
%       Copyright (c) 2015 Kristen M. Thyng
%   MATLAB function cmocean.m, https://github.com/chadagreene/cmocean
%       Copyright (c) 2021 Chad Greene
%   Both are distributed under the MIT License:
%
